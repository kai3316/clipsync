def test_a_relay_blip_does_not_blank_what_is_already_on_screen():
    """A reconnect refreshes behind the reader instead of clearing the panel.

    The desktop's tunnel really does hop between public brokers when one drops
    it.  Every hop used to re-run the page's "first load" path: history became a
    skeleton, chat was rebuilt, and if the reconnect raced the read it showed
    加载失败.  The recovery path is now silent, the chat view is only rebuilt
    when the transcript actually changed, and a returning tab tells the relay
    to re-ping the computer instead of rotating a healthy tunnel over throttled
    background misses.
    """
    root = Path(__file__).resolve().parents[1]
    html = (root / "internal" / "web" / "static" / "mobile.html").read_text(encoding="utf-8")
    assert "loadTab(activeTabName(), true)" in html
    assert "chatComputerSigPrev" in html
    assert "window.__CLIPSYNC_REMOTE__.wake" in html
    # A tab that has content must never take the "first visit" skeleton path.
    assert "blank panel reads as a broken page" in html
    transport = (root / "internal" / "web" / "static" / "remote-transport.js").read_text(
        encoding="utf-8"
    )
    assert "Tunnel.prototype.wake" in transport
    assert "sendPresencePing" in transport


def test_the_page_refreshes_from_pushed_events_and_explains_an_error_status():
    """Push events replace most of the remote polling, and errors are named.

    The tunnel already carries the runtime's events (clipboard changed, chat
    message...).  The page consumes them, so the reader sees a change when it
    happens instead of up to a poll later -- and the poll can run slower, which
    is what keeps the phone under the desktop's 20-reads-a-minute budget.  A
    status the reader can act on (companion stopped = 503, read-only = 501,
    pacing = 429) is shown instead of the generic "relay is connecting".
    """
    root = Path(__file__).resolve().parents[1]
    html = (root / "internal" / "web" / "static" / "mobile.html").read_text(encoding="utf-8")
    transport = (root / "internal" / "web" / "static" / "remote-transport.js").read_text(
        encoding="utf-8"
    )
    assert "frame.type === 'evt'" in transport
    assert "Tunnel.prototype.emitEvent" in transport
    assert "onEvent: function" in transport
    assert "handleRelayEvent" in html
    assert "relayEventReload" in html
    # A user action retries through a 429 instead of reporting a failed action.
    assert "apiFetchAttempt" in html
    # Actionable failure text for the statuses the tunnel can return.
    assert "failCompanionDown" in html
    assert "err.status === 503" in html
    assert "err.status === 501" in html
    # Remote polling is paced: events carry the changes.
    assert "lastRemotePollAt" in html


def test_a_bookmarked_page_resumes_its_saved_pairing():
    """The QR code only has to be scanned once per browser profile.

    The token arrives in the URL fragment, and a bookmark or home-screen icon
    opens the bare page URL, which has none.  The page used to rely on
    sessionStorage alone, so every bookmarked open looked unpaired and anything
    that sends failed against the static host.  The pairing is now persisted per
    origin and resumed when there is no fragment; a 403 (rotated token) clears
    it, and a page that resumed its pairing says "re-scan" after repeated
    failures because a rotated key cannot be reported any other way.
    """
    root = Path(__file__).resolve().parents[1]
    transport = (root / "internal" / "web" / "static" / "remote-transport.js").read_text(
        encoding="utf-8"
    )
    html = (root / "internal" / "web" / "static" / "mobile.html").read_text(encoding="utf-8")
    assert "PERSIST_KEY" in transport
    assert "savePersistent" in transport
    assert "loadPersistent" in transport
    assert "forgetPersistent" in transport
    # Resumed *only* when neither the fragment nor the same-tab session is there.
    marker = "// ---------------------------------------------------------------- entry"
    entry = transport[transport.index(marker):]
    assert "config = loadPersistent();" in entry
    # The page drops a rejected pairing and warns after a run of failures.
    assert "forgetPairing" in html
    assert "resumedPairing" in html
    assert "relayRescanHint" in html


