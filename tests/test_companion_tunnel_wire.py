"""Phase-0 wire vectors shared with the PWA's WebCrypto implementation.

The phone derives its channel key with HKDF-SHA256 and seals frames with
AES-256-GCM in the browser.  These vectors are the contract between that code
and this side: a change to the salt, info, hash, nonce length or prefix fails
here before it can ship as "the phone connects but every frame is rejected".

The vectors were generated by the Python implementation for the key and the
envelope, and by Node's WebCrypto for the sealed body; each side checks the
other's output.
"""

import base64
import json

from internal.security.encryption import decrypt
from internal.transport.companion_tunnel import derive_key
from internal.transport.relay import open_envelope

TOKEN = "test-token-0123456789abcdef"
KEY_HEX = "6670f02c7fb014934ef0f673dbcea400cc852ae0529ca0af283e931d60b941b4"

# Python -> JS: a full relay envelope around {"v":1,"type":"ping"} at ts 1000000.
PYTHON_ENVELOPE_B64 = (
    "eyJ2IjoxLCJ0cyI6MTAwMDAwMC4wLCJkYXRhIjoiQVVOQ1JmbG10aEpPdGxJMzNlVjkySWh3YlF5aDNaNWI3K1A1"
    "c2dwblcvMWY0ZDM3cTZvRzV3UnRwNzRxY29XaHZNRCtudTg9IiwibWFjIjoiOTY0OWEyZjE2MGMyMDA3NmFiNjUx"
    "YTI4NzJlMzU4OGZkNjgzMTBkNjIwYzlhZWQ2MjVlZmNiZmJiMTM5YWQ4ZCJ9"
)
# JS -> Python: b"\x01CBE" + iv(00..0b) + AES-GCM({"v":1,"type":"pong"}).
JS_SEALED_B64 = "AUNCRQABAgMEBQYHCAkKC4KLolLmASD0AD93nGqGrT8j8G9gfj0gXwEBQCfnE9nY/Yiw3+g="
JS_PLAIN_B64 = "eyJ2IjoxLCJ0eXBlIjoicG9uZyJ9"


def test_the_phone_and_desktop_derive_the_same_key():
    assert derive_key(TOKEN).hex() == KEY_HEX


def test_the_desktop_can_open_the_envelope_the_test_proves_the_pwa_will_send():
    inner = open_envelope(
        base64.b64decode(PYTHON_ENVELOPE_B64), bytes.fromhex(KEY_HEX), 1_000_000.0
    )
    assert inner is not None
    assert json.loads(inner) == {"v": 1, "type": "ping"}


def test_the_desktop_can_decrypt_the_bodyshape_webcrypto_produces():
    sealed = base64.b64decode(JS_SEALED_B64)
    assert sealed[:4] == b"\x01CBE"
    plain = decrypt(sealed, bytes.fromhex(KEY_HEX))
    assert plain == base64.b64decode(JS_PLAIN_B64)
